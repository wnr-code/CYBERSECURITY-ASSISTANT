  String text(String source) {
    if (locale.languageCode == 'id') return _id[source] ?? source;
    final explicitEnglish = _en[source];
    if (explicitEnglish != null) return explicitEnglish;
    for (final entry in _id.entries) {
      if (entry.value == source) return entry.key;
    }
    return source;
  }

  static AppLocalizations of(BuildContext context) => Localizations.of<AppLocalizations>(context, AppLocalizations)!;
}

extension AppLocalizationContext on BuildContext {
  String tr(String source) => AppLocalizations.of(this).text(source);
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales.any((supported) => supported.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) => SynchronousFuture(AppLocalizations(locale));

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}
